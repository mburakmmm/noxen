#!/usr/bin/env python3
"""
scripts/verify_json_schema.py
Independent standards-compliance validator for JSON Schema generated by Noxen.
Validates Noxen's output against the official Draft 2020-12 specification using jsonschema.
"""

import subprocess
import json
import sys
from jsonschema import Draft202012Validator, validate, ValidationError

def main():
    print("1. Running scripts/dump_schemas.nox via noxc...")
    res = subprocess.run(
        ["noxc", "run", "scripts/dump_schemas.nox"],
        capture_output=True,
        text=True,
        check=True
    )

    output = res.stdout
    start_tag = "---SCHEMA_START---"
    end_tag = "---SCHEMA_END---"
    start_idx = output.find(start_tag)
    end_idx = output.find(end_tag)

    if start_idx == -1 or end_idx == -1:
        print("ERROR: Could not find schema tags in noxc output:")
        print(output)
        sys.exit(1)

    schema_text = output[start_idx + len(start_tag):end_idx].strip()
    schema = json.loads(schema_text)

    print("2. Validating Noxen schema against official JSON Schema Draft 2020-12 metaschema...")
    # This verifies the schema itself is 100% valid Draft 2020-12!
    Draft202012Validator.check_schema(schema)
    print("   [OK] Noxen schema strictly conforms to Draft 2020-12 metaschema.")

    validator = Draft202012Validator(schema)

    print("3. Validating conforming instance...")
    valid_instance = {
        "id": 100,
        "username": "ada_lovelace",
        "email": "ada@example.com",
        "website": "https://example.com/ada",
        "created_at": "2026-10-26T12:00:00Z",
        "tags": ["pioneer", "compiler"],
        "employer": {
            "name": "Acme Computing",
            "tax_id": "ACM-9921",
            "headquarters": {
                "street": "Baker Street 221B",
                "city": "London",
                "zip_code": "NW16XE"
            }
        },
        "previous_employers": [
            {
                "name": "Babbage Analytical Engines",
                "tax_id": "BAB-1837",
                "headquarters": {
                    "street": "Main Street 1",
                    "city": "Cambridge",
                    "zip_code": "CB21TN"
                }
            }
        ]
    }
    validator.validate(valid_instance)
    print("   [OK] Conforming instance passed validation.")

    print("4. Validating non-conforming instances (rejection verification)...")
    # Test A: Negative integer for id (minimum is 1)
    bad_id = dict(valid_instance, id=0)
    errors = list(validator.iter_errors(bad_id))
    assert len(errors) > 0, "Expected error for id < 1"
    print("   [OK] Rejection verified: id < 1 rejected by independent validator.")

    # Test B: Invalid pattern for tax_id
    bad_tax = json.loads(json.dumps(valid_instance))
    bad_tax["employer"]["tax_id"] = "invalid tax id with spaces & symbols!"
    errors = list(validator.iter_errors(bad_tax))
    assert len(errors) > 0, "Expected error for invalid pattern"
    print("   [OK] Rejection verified: invalid regex pattern rejected.")

    # Test C: Missing required field
    bad_missing = dict(valid_instance)
    del bad_missing["username"]
    errors = list(validator.iter_errors(bad_missing))
    assert len(errors) > 0, "Expected error for missing required field"
    print("   [OK] Rejection verified: missing required field rejected.")

    print("\nALL INDEPENDENT JSON SCHEMA DRAFT 2020-12 VALIDATIONS PASSED SUCCESSFULLY!")

if __name__ == "__main__":
    main()
